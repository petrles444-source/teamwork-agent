"""Сторож кодировки: ловить двойное кодирование, пока текст ещё можно спасти.

Зачем этот файл существует. Русский текст, записанный UTF-8, прочитанный как
cp1251 и сохранённый снова, превращается в «Р°СЂС‚РµС‚Р°Рё»: буквы, за
которыми стоят знак градуса, микро-сигна и европейская кавычка вместо
запятой. Файл при этом ПРОХОДИТ все тесты — страдают только docstring'и и
сообщения утверждений, а код работает. Красного гейта не было ни разу, и
рассуждение, ради которого файл написан, было недоступно никому, включая
автора.

Причина известная и повторяющаяся: PowerShell 5.1 пишет с BOM и перечитывает
UTF-8 как cp1251. Восстановление возможно, пока цел каждый байт; при потере
части символов обращение становится неполным, и часть слов остаётся битой
навсегда. Поэтому ловить надо в день появления файла, а не через месяц.

Инструмент починки в шаблоне есть — `scripts/agent_handoff.py
repair-encoding`. Не хватало обнаружения.

## Почему маркеры именно такие

Двойное кодирование превращает два байта UTF-8 в два символа, где ВТОРОЙ
лежит ВНЕ кириллического блока: знак градуса, микро-сигна, европейская
кавычка. В нормальном русском тексте таких сочетаний не бывает, поэтому
они годятся для проверки без ложных срабатываний.

В `scripts/agent_handoff.py` есть готовый MOJIBAKE_PAIRS, но он наполовину
состоит из пар «кириллица + кириллица» («Рё», «Рє», «Сѓ»), а такие
встречаются в обычном тексте. Для починки это безвредно, для гейта — источник
ложных тревог: гейт, который краснеет на нормальном файле, выключают целиком,
и вместе с ним исчезает всё, ради чего он поставлен.

Маркеры собираются через `chr()`, а не пишутся литералами, чтобы сам этот
файл не содержал искомые последовательности и не срабатывал на себе.
"""

from __future__ import annotations

from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parent.parent

#: Расширения, которые имеет смысл проверять.
TEXT_SUFFIXES = {".py", ".md", ".toml", ".yml", ".yaml", ".json", ".bat",
                 ".txt", ".cfg", ".html"}

#: Каталоги вне проекта: зависимости, артефакты, чужие рабочие файлы.
SKIP_DIRS = {
    ".venv", "venv", "node_modules", ".git", "__pycache__", ".pytest_cache",
    ".ruff_cache", ".mypy_cache", ".benchmarks", ".tox", ".nox", "build",
    "dist", "*.egg-info",
}

#: Символ замены U+FFFD. Через chr(), а не литералом: литерал означал бы,
#: что этот файл срабатывает на себе сам.
REPLACEMENT = chr(0xFFFD)


#: Хвосты, годные для ГЕЙТА. Отобраны замером, а не вкусом.
#:
#: Двойное кодирование кладёт рядом кириллическую букву и символ ВНЕ
#: кириллического блока. Но «вне блока» — недостаточно: некоторые из таких
#: символов являются обычной русской типографикой и стоят после кириллицы
#: в нормальном тексте.
#:
#: Условие проверки строгое: буква и символ стоят ПОДРЯД, без пробела. Именно
#: поэтому русское тире «слово — слово» (всегда с пробелами) не мешает, а
#: многоточие «загрузка…» (слитно) мешает. Проверка на живом материале:
#: `test_every_excluded_tail_has_a_measured_justification` требует обоснования
#: для каждого исключённого хвоста и требует вернуть в набор любой хвост,
#: который в нормальном тексте не встречается.
SAFE_TAILS = (0xB0, 0xB5, 0xB7, 0x2014, 0x2019, 0x201A, 0x201C, 0x20AC)

#: Хвосты, годные только для ПОЧИНКИ, и не для гейта.
#:
#: Исключены по измерению, и измерение воспроизводится тестом:
#:
#:   U+2026 …  «загрузка…»        — многоточие слитно с буквой, обычный текст
#:   U+201D ”  «сказал ”цитата”»   — закрывающая английская кавычка
#:
#: Оба символа при этом ПРИСУТСТВУЮТ в результате настоящей порчи, поэтому
#: repair-encoding их знает: для починки лишний маркер безвреден, для гейта —
#: источник ложных срабатываний. Гейт, который краснеет на нормальном файле,
#: отключают целиком, и вместе с ним исчезает всё, ради чего он поставлен.
REPAIR_ONLY_TAILS = (0x201D, 0x2026)

#: Кириллические буквы, которые могут стоять первыми в паре.
HEADS = (0x410, 0x420, 0x430, 0x440, 0x450, 0x425)


def _mojibake_pairs(tails=SAFE_TAILS) -> tuple[str, ...]:
    """Пары «кириллица + не-кириллица», возможные только при двойном кодировании."""
    return tuple(chr(h) + chr(t) for h in HEADS for t in tails)


PAIRS = _mojibake_pairs()


def _allowed() -> dict[str, str]:
    """Файлы, которые содержат искомые последовательности СПЕЦИАЛЬНО.

    Без такого списка проверка краснеет на собственных фикстурах — а гейт,
    который краснеет на нормальном файле, отключают целиком.

    Причина обязательна: иначе через месяц сюда добавят ещё одну строку «пока
    не мешает», и реальная порча спрячется среди легитимных.
    """
    return {
        "scripts/agent_handoff.py":
            "определяет MOJIBAKE_PAIRS — сами последовательности-маркеры",
        "tests/test_agent_handoff.py":
            "фикстуры для проверки починки мохибейка",
        "tests/test_text_encoding.py":
            "собирает образцы через chr() и хранит их описание",
    }


def _iter_text_files():
    for path in ROOT.rglob("*"):
        if not path.is_file() or path.suffix.lower() not in TEXT_SUFFIXES:
            continue
        relative = path.relative_to(ROOT)
        if SKIP_DIRS.intersection(relative.parts):
            continue
        if any(part.startswith("pytest-of-") for part in relative.parts):
            continue
        if ".egg-info" in relative.parts:
            continue
        yield path


def _find_problems(text: str) -> list[str]:
    problems = []
    if REPLACEMENT in text:
        line = text[: text.index(REPLACEMENT)].count("\n") + 1
        problems.append(f"строка {line}: символ замены {REPLACEMENT!r}")
    hits = sum(text.count(p) for p in PAIRS)
    if hits:
        example = next(p for p in PAIRS if p in text)
        line = text[: text.index(example)].count("\n") + 1
        problems.append(
            f"{hits} совпадений двойного кодирования (например {example!r}), "
            f"первое — строка {line}"
        )
    return problems


@pytest.mark.parametrize(
    "path", sorted(_iter_text_files()), ids=lambda p: str(p.relative_to(ROOT))
)
def test_text_files_are_not_double_encoded(path: Path):
    """Каждый текстовый файл обязан читаться как UTF-8 и говорить по-русски.

    Сообщение содержит причину и способ починки, потому что человек, который
    увидит это, скорее всего, только что закрыл редактор.
    """
    raw = path.read_bytes()
    try:
        text = raw.decode("utf-8-sig")
    except UnicodeDecodeError as exc:
        pytest.fail(
            f"{path.relative_to(ROOT)} не читается как UTF-8: {exc}. "
            "Починить: scripts/agent_handoff.py repair-encoding"
        )

    relative = path.relative_to(ROOT).as_posix()
    problems = _find_problems(text)
    if problems and relative in _allowed():
        return
    assert not problems, (
        f"{relative}: " + "; ".join(problems) + "\n"
        "Причина: файл записан в UTF-8, прочитан как cp1251 и сохранён снова.\n"
        "Починить: scripts/agent_handoff.py repair-encoding "
        "(восстановление возможно, пока цел каждый байт)\n"
        "Не повторять: PowerShell 5.1 Set-Content/Out-File добавляет BOM и "
        "перечитывает UTF-8 как cp1251. Писать средствами Python с "
        "encoding='utf-8'."
    )


def test_detector_does_not_flag_ordinary_russian():
    """Сторож обязан молчать на нормальном тексте, иначе его выключат.

    Слова с настоящими кириллическими парами («скорость», «Рёбра») — именно
    тот случай, который отличает рабочий детектор от шумного.
    """
    sample = (
        "Скорость сбора: 22 559 записей. Режём по /24, ловим дубль.\n"
        "Рёбра жёсткости; «умолчание» в кавычках; цена — 0,30 с.\n"
    )
    assert _find_problems(sample) == []


def _broken_sample() -> str:
    """Настоящий мохибейк, собранный из кодов, а не вставленный литералом."""
    return "".join(chr(c) for c in (0x422, 0x420, 0xB0, 0x438, 0x430, 0x201A))


def test_detector_catches_real_double_encoding():
    """Проверка на самом детекторе: он обязан видеть настоящую порчу."""
    assert _find_problems(_broken_sample()), "детектор не заметил очевидный мохибейк"


def test_detector_catches_replacement_character():
    assert _find_problems("строка с битым символом: " + REPLACEMENT)


def test_scan_is_not_vacuous():
    """Проверяемых файлов должно быть много — иначе фильтры съели всё.

    Пустой список означал бы, что сторож проходит, ничего не делая. Это
    худший вид зелёного гейта: он выглядит как работающая защита.
    """
    assert len(list(_iter_text_files())) > 10, (
        "скан почти пуст — фильтры слишком злые, сторож ничего не проверяет"
    )


def test_repair_tool_exists_and_is_advertised_correctly():
    """Инструмент починки обязан существовать, иначе подсказка врёт."""
    source = (ROOT / "scripts" / "agent_handoff.py").read_text(encoding="utf-8-sig")
    assert "def repair_mojibake_in_place" in source


def test_allowlist_entries_all_exist():
    """Каждая запись в списке исключений обязана указывать на реальный файл.

    Иначе исключение остаётся, а файла, к которому оно относится, уже нет —
    и настоящая порча в нём больше не заметна.
    """
    stale = [name for name in _allowed() if not (ROOT / name).exists()]
    assert stale == [], f"список исключений ссылается на несуществующие файлы: {stale}"


# --- почему набор маркеров именно такой -------------------------------------

def _round_trip(text: str) -> str:
    """Настоящее двойное кодирование: UTF-8 прочитан как cp1251."""
    return text.encode("utf-8").decode("cp1251")


CLEAN_SAMPLES = (
    "Скорость сбора: 22 559 записей. Режём по /24, ловим дубль.",
    "Рёбра жёсткости; «умолчание» в кавычках; цена — 0,30 с.",
    "Проверка живости занимает 25 мс на адрес — бюджет не выполняется.",
    "Слово «загрузка…» и ещё один пример: значение — 1,5 с.",
    "Он сказал ”цитата” без пробела, а потом — тире.",
    "счётчик—индикатор без пробелов тоже встречается",
    "температура 25°C и градус",
    "разделитель · средняя точка",
    "слово…многоточие",
    "„нижняя кавычка” в начале",
    "итого 5\u20ac и евро",
)


def test_markers_catch_a_real_round_trip():
    """ГЛАВНАЯ проверка набора маркеров: он обязан видеть настоящую порчу.

    Образец получен настоящим двойным кодированием, а не собран из кодов
    вручную: ручная сборка проверяла бы ту строку, которую сам же и придумал,
    и пропустила бы другой вариант порчи.
    """
    broken = _round_trip(
        "Скорость сбора упала: 22 559 записей в секунду, дубли отфильтрованы."
    )
    assert _find_problems(broken), "набор маркеров не видит настоящий мохибейк"


def test_markers_survive_a_truncated_round_trip():
    """Порча часто обрезана — файл перезаписали, символы потерялись.

    Обрезанный образец обязан распознаваться так же: иначе сторож молчит
    именно там, где восстановление уже невозможно, и агент тратит день,
    выясняя, почему repair-encoding не помогает.
    """
    broken = _round_trip("Проверка живости занимает 25 мс на адрес")[:40]
    assert _find_problems(broken), "обрезанная порча не распознана"


def test_markers_do_not_collide_with_ordinary_typography():
    """Вторая половина контракта, и она важнее первой.

    Набор маркеров расширяют по мере появления новых символов. Каждое
    расширение выглядит безобидно, и каждое может добавить обычную
    типографику: многоточие «загрузка…», тире «слово — слово», английские
    кавычки ”слово”. Гейт, который краснеет на нормальном файле, отключают
    целиком — и вместе с ним исчезает всё, ради чего он поставлен.

    Поэтому проверка обязана быть НЕРАЗРЕШИМОЙ: любой обычный текст обязан
    проходить. Список образцов ниже расширяют по мере находок.
    """
    collisions = [s for s in CLEAN_SAMPLES if _find_problems(s)]
    assert collisions == [], (
        f"набор маркеров совпал с обычной типографикой: {collisions}"
    )


def test_every_excluded_tail_has_a_measured_justification():
    """Каждый исключённый хвост обязан быть исключён ПО ИЗМЕРЕНИЮ.

    Тест фиксирует не список, а обоснование: хвост попадает в
    REPAIR_ONLY_TAILS только если он действительно совпадает с обычной
    типографикой хотя бы в одном нормальном образце. Иначе исключение
    остаётся «на всякий случай», а через полгода кто-то возвращает его в
    маркеры, потому что исключение выглядит бессмысленным.

    Второй конец контракта: хвост, который НЕ совпадает ни с одним
    нормальным образцом, обязан быть в SAFE_TAILS — иначе мы молча теряем
    покрытие настоящей порчи.
    """
    def collides(tail: int) -> bool:
        pairs = _mojibake_pairs(tails=(tail,))
        return any(p in sample for sample in CLEAN_SAMPLES for p in pairs)

    unjustified = [t for t in REPAIR_ONLY_TAILS if not collides(t)]
    assert unjustified == [], (
        f"хвосты исключены без измерения, они годятся для гейта: "
        f"{[hex(t) for t in unjustified]}"
    )

    unjustified_safe = [t for t in SAFE_TAILS if collides(t)]
    assert unjustified_safe == [], (
        f"хвосты оставлены в маркерах, хотя совпадают с нормальным текстом: "
        f"{[hex(t) for t in unjustified_safe]}"
    )


def test_scanning_the_repository_stays_silent():
    """Проверка на живом материале: весь заведомо нормальный текст репозитория.

    Предыдущие тесты работают на придуманных образцах и ничего не говорят
    о том, что детектор молчит на реальных файлах. Этот говорит: прогоняет
    все текстовые файлы и требует ноль находок вне списка исключений.
    """
    offenders = []
    for path in _iter_text_files():
        relative = path.relative_to(ROOT).as_posix()
        if relative in _allowed():
            continue
        try:
            text = path.read_bytes().decode("utf-8-sig")
        except UnicodeDecodeError:
            continue  # об этом сообщает основной параметризованный тест
        problems = _find_problems(text)
        if problems:
            offenders.append(f"{relative}: {problems[0]}")
    assert offenders == [], (
        "детектор срабатывает на нормальных файлах репозитория — значит, "
        f"набор маркеров слишком широк и будет отключён: {offenders}"
    )
